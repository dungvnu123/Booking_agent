CREATE TABLE IF NOT EXISTS roles (
 role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 role_name VARCHAR(50) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS auth_role_name_unique ON roles(role_name);

CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(255) PRIMARY KEY,
 role_id BIGINT REFERENCES roles(role_id),
 username VARCHAR(50),
 full_name VARCHAR(200),
 email VARCHAR(200),
 password_hash VARCHAR(255),
 phone VARCHAR(20),
 is_active BOOLEAN,
 last_login_at TIMESTAMP,
 created_at TIMESTAMP,
 updated_at TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS auth_user_email_unique ON users(lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS auth_user_phone_unique ON users(phone) WHERE phone IS NOT NULL AND phone<>'';

CREATE TABLE IF NOT EXISTS patients (
 id VARCHAR(50) PRIMARY KEY,
 patient_code VARCHAR(50),
 full_name VARCHAR(200),
 date_of_birth DATE,
 gender VARCHAR(10),
 phone VARCHAR(20),
 email VARCHAR(255),
 job VARCHAR(50),
 address TEXT,
 allergies TEXT,
 blood_type VARCHAR(5),
 insurance_id VARCHAR(50),
 citizen_id VARCHAR(12),
 cooperation_ability VARCHAR(50),
 created_at TIMESTAMP,
 updated_at TIMESTAMP,
 last_visit_date DATE,
 user_id VARCHAR(255) UNIQUE REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS auth_patient_phone_idx ON patients(phone);

CREATE TABLE IF NOT EXISTS invalidated_token (
 id_token VARCHAR(255) PRIMARY KEY,
 expiry_time TIMESTAMPTZ NOT NULL
);

INSERT INTO roles(role_name)
VALUES ('ADMIN'),('MANAGER'),('DOCTOR'),('RECEPTIONIST'),('PATIENT')
ON CONFLICT(role_name) DO NOTHING;
